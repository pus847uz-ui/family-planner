// Постоянное меню в личке с ботом.
//
// Обычная клавиатура, а не кнопки под сообщением: инлайновые живут при своём сообщении
// и уезжают вверх с перепиской, а меню должно быть под рукой всегда. Нажатие присылает
// обычный текст — его и ловим, поэтому подписи кнопок обязаны совпадать с ключами карты
// ровно, вместе с эмодзи.
const { WEBAPP_URL } = require("./config");

// Кнопка — это заготовленный вопрос, а не отдельная ветка логики: ответ на неё идёт тем
// же путём, что и /ask, с той же памятью и той же записью в историю.
const MENU_QUESTIONS = {
  "📋 Мои задачи": "что мне нужно сделать",
  "🛒 Что купить": "что нужно купить",
  "📅 Что впереди": "какие ближайшие события",
  "💰 Платежи": "какие регулярные платежи и когда их вносить",
  "💡 Как пользоваться": "коротко расскажи, как пользоваться планировщиком и что ты умеешь",
};

function mainMenuKeyboard() {
  return {
    keyboard: [
      [{ text: "📋 Мои задачи" }, { text: "🛒 Что купить" }],
      [{ text: "📅 Что впереди" }, { text: "💰 Платежи" }],
      [{ text: "💡 Как пользоваться" }, { text: "📱 Планировщик", web_app: { url: WEBAPP_URL } }],
    ],
    resize_keyboard: true,
    // Меню остаётся после нажатия и переживает перезапуск клиента: без этого человеку
    // пришлось бы звать /start каждый раз, когда клавиатура схлопнулась.
    is_persistent: true,
    input_field_placeholder: "Спросите о планах",
  };
}

function menuQuestionFor(text) {
  return MENU_QUESTIONS[(text || "").trim()] || null;
}

module.exports = { mainMenuKeyboard, menuQuestionFor, MENU_QUESTIONS };
